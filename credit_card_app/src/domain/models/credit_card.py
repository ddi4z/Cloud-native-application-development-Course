from datetime import datetime
from enum import Enum
from typing import Optional

from pydantic import BaseModel, EmailStr, Field


class CreditCardStatus(str, Enum):
    """Enum for cc status."""

    PENDING_VERIFICATION = "POR_VERIFICAR"
    REJECTED = "RECHAZADA"
    APPROVED = "APROBADA"


class CreditCardIssuer(str, Enum):
    """Enum for Credit Card Issuers"""
    VISA = "VISA"
    MC = "MASTERCARD"
    AC = "AMERICAN EXPRESS"
    D = "DISCOVER"
    DC = "DINERS CLUB"
    NO_INFO = "UNKNOWN"


class CreditCard(BaseModel):
    """Credit Card domain model."""

    id: str = Field(description="User identifier in UUID format")
    token: str = Field(min_length=256, max_length=256, description=" token generated by the platform")
    userId: str = Field(description="User owning the credit card, in UUID format")
    lastFourDigits: str = Field(description="Credit card's last four digits", min_length=4, max_length=4)
    ruv: str = Field(description="Reistro único de verificación")
    issuer: CreditCardIssuer = Field(description="CC issuer")
    status: CreditCardStatus = Field(description="Current user status")
    createdAt: datetime = Field(description="Date and time when the user was created")
    updatedAt: datetime = Field(description="Date and time when the user was last updated"
    )
